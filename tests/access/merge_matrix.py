#!/usr/bin/env python3
"""Builds the committed access matrix from what the matrix test wrote (ch-4pn.17.1).

    CH_MATRIX_OUT=/work/tests/access/.gen cargo nextest run -p codehaven --test access_matrix
    python3 tests/access/merge_matrix.py tests/access/.gen

Each cell test writes `<credential>.<column>.<tier>.txt` with one `<code> <METHOD> <pattern>` line
per request that was not refused, and the first of them also writes `routes.txt`. This joins the
six columns of a credential into `matrix.<credential>.txt`, one row per route and method with six
cells, and copies the route list to `matrix.routes.txt`. Only a person runs this, on purpose, and
reads the diff: every changed cell is a change in what a credential can reach.
"""
import sys
from pathlib import Path

CREDS = ["none", "session", "basic", "pat_read", "pat_write", "job_read", "job_write", "job_other", "runner", "app"]
COLUMNS = ["private / everyone", "private / limited", "internal / everyone", "internal / limited", "public / everyone", "public / limited"]
METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE"]
HERE = Path(__file__).resolve().parent


def order(key):
    method, pattern = key.split(" ", 1)
    return (pattern, METHODS.index(method) if method in METHODS else 9)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    gen = Path(sys.argv[1])
    for cred in CREDS:
        rows = {}
        for col in range(6):
            files = list(gen.glob(f"{cred}.{col}.*.txt"))
            if len(files) != 1:
                sys.exit(f"merge_matrix: expected one file for {cred} column {col} in {gen}, found {len(files)}")
            for line in files[0].read_text().splitlines():
                code, key = line.split(" ", 1)
                rows.setdefault(key, ["."] * 6)[col] = code
        out = [
            f"# What a `{cred}` credential reaches (ch-4pn.17.1). Generated by merge_matrix.py from access_matrix.rs; read the diff.",
            "# Columns, left to right: " + ", ".join(COLUMNS) + " (tier / who may contribute).",
            "# . refused (401, 403, 404, 405 or the redirect to sign in)   v answered, but the request was not valid (400, 413, 415, 422)   r answered, rows and refs unchanged   w answered and changed rows or refs",
            "# Rows that are refused in every column are not listed. Routes are in matrix.routes.txt.",
        ]
        out += [f"{''.join(cells)} {key}" for key, cells in sorted(rows.items(), key=lambda kv: order(kv[0]))]
        (HERE / f"matrix.{cred}.txt").write_text("\n".join(out) + "\n")
        print(f"matrix.{cred}.txt: {len(rows)} rows")
    routes = (gen / "routes.txt").read_text().splitlines()
    (HERE / "matrix.routes.txt").write_text(
        "# Every route the router registers (ch-4pn.17.1). A route not listed here fails every_registered_route_has_a_row_in_the_matrix.\n"
        + "\n".join(sorted(routes)) + "\n"
    )
    print(f"matrix.routes.txt: {len(routes)} routes")


if __name__ == "__main__":
    main()
